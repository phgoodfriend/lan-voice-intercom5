/**
 * Normalize a MAC address to "XX:XX:XX:XX:XX:XX" uppercase format.
 */
function normalizeMac(mac) {
  if (!mac) return '';
  return mac
    .replace(/-/g, ':')
    .toUpperCase()
    .split(':')
    .map((seg) => seg.padStart(2, '0'))
    .join(':');
}

/**
 * Look up the vendor name from a full MAC address. Returns "Unknown" if
 * the OUI prefix is not in the table, or the MAC is empty/invalid.
 */
function lookupVendor(mac) {
  if (!mac) return 'Unknown';
  const normalized = normalizeMac(mac);
  const prefix = normalized.split(':').slice(0, 3).join(':');
  return OUI_MAP[prefix] || 'Unknown';
}

